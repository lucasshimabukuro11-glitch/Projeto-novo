import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function persona(page: Page, role: string) {
  await page.goto('/entrar')
  await page.getByRole('button',{ name: role,exact: true }).click()
}

test('organizador edita o mapa e participante escolhe assento com identificação acessível', async ({ page: owner,context }) => {
  await persona(owner,'Organizador')
  await owner.goto('/organizacao/eventos/tech-summit-brasil/configuracao')
  await owner.getByText('Novo setor',{ exact: true }).click()
  const sector = owner.locator('details').filter({ has: owner.getByText('Novo setor',{ exact: true }) })
  await sector.getByLabel('Nome do setor').fill('Sala de debates')
  await sector.getByLabel('Capacidade do setor').fill('5')
  await sector.getByRole('button',{ name: 'Criar setor' }).click()
  await expect(owner.getByText('Sala de debates',{ exact: false }).first()).toBeVisible()
  await owner.getByText('Nova modalidade',{ exact: true }).click()
  const type = owner.locator('details').filter({ has: owner.getByText('Nova modalidade',{ exact: true }) })
  await type.getByLabel('Nome da modalidade').fill('Cortesia')
  await type.getByLabel('Setor associado').selectOption({ label: 'Sala de debates' })
  await type.getByLabel('Quantidade disponível').fill('5')
  await type.getByRole('button',{ name: 'Criar modalidade' }).click()
  await expect(type.getByText('Configuração salva.')).toBeVisible()
  await owner.getByRole('button',{ name: 'Assentos',exact: true }).click()
  await expect(owner.getByRole('heading',{ name: 'Mapa de assentos' })).toBeVisible()
  await owner.getByLabel('Tipo para aplicar').selectOption('accessible')
  await owner.getByRole('button',{ name: 'A2 · Disponível' }).click()
  await expect(owner.getByRole('button',{ name: 'A2 · Acessível' })).toBeVisible()
  await owner.getByRole('button',{ name: 'Salvar mapa' }).click()
  await expect(owner.getByText('Mapa de assentos salvo.')).toBeVisible()

  const participant = await context.newPage()
  await participant.setViewportSize({ width: 390,height: 844 })
  await persona(participant,'Participante')
  await participant.goto('/eventos/tech-summit-brasil')
  await expect(participant.getByLabel('Modalidade do ingresso')).toContainText('VIP')
  await participant.getByRole('button',{ name: 'A2 · Acessível' }).click()
  await expect(participant.getByText('Assento A2 selecionado.')).toBeVisible()
  expect(await participant.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await participant.getByRole('button',{ name: 'Reservar ingresso' }).click()
  await expect(participant.getByText('Pista · Auditório universitário · Assento A2')).toBeVisible()
  const code = await participant.getByLabel('Código do ingresso').inputValue()

  const staff = await context.newPage()
  await persona(staff,'Equipe de check-in')
  await staff.goto('/check-in?evento=tech-summit-brasil')
  await staff.getByLabel('Portaria em atendimento').selectOption({ label: 'Portaria VIP' })
  await staff.getByLabel('Código do ingresso').fill(code)
  await staff.getByRole('button',{ name: 'Validar ingresso' }).click()
  await expect(staff.getByRole('heading',{ name: 'Acesso negado — setor não autorizado' })).toBeVisible()

  await owner.goto('/organizacao/monitoramento?evento=tech-summit-brasil')
  const present = owner.locator('article[aria-label="Presentes"] strong')
  await expect(present).toHaveText('1')
  await owner.getByLabel('Dados do gráfico').selectOption('sector')
  await expect(owner.getByRole('heading',{ name: 'Ocupação por setor',exact: true })).toBeVisible()
  await staff.getByLabel('Portaria em atendimento').selectOption({ label: 'Portaria Auditório' })
  await staff.getByLabel('Código do ingresso').fill(code)
  await staff.getByRole('button',{ name: 'Validar ingresso' }).click()
  await expect(staff.getByRole('heading',{ name: 'Entrada autorizada' })).toBeVisible()
  await expect(present).toHaveText('2')
  await expect(staff.getByText('Pista · Setor Auditório universitário · Assento A2')).toBeVisible()

  await owner.getByRole('link',{ name: 'Abrir auditoria' }).click()
  await owner.getByLabel('Resultado').selectOption('wrong_sector')
  await owner.getByRole('button',{ name: 'Aplicar filtros' }).click()
  await expect(owner.getByRole('heading',{ name: '1 ocorrências encontradas' })).toBeVisible()
  const exporting = owner.waitForEvent('download')
  await owner.getByRole('button',{ name: 'Exportar CSV' }).click()
  const exported = await exporting
  const report = await readFile((await exported.path())!,'utf8')
  expect(report).toContain('Portaria VIP')
  expect(report).toContain('setor não autorizado')
})

test('certificado acadêmico gera PDF e código consultável pelo público', async ({ page }) => {
  await persona(page,'Participante')
  await page.getByRole('link',{ name: 'Meus certificados' }).click()
  await expect(page.getByRole('heading',{ name: 'Jornada Universitária de Inovação' })).toBeVisible()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button',{ name: 'Baixar certificado em PDF' }).click()
  const downloaded = await downloading
  expect(downloaded.suggestedFilename()).toMatch(/^eventscan-certificado-.*\.pdf$/)
  const pdf = await readFile((await downloaded.path())!)
  expect(pdf.toString('utf8',0,5)).toBe('%PDF-')
  await page.locator('.certificate-card').getByRole('link',{ name: 'Verificar certificado' }).click()
  await expect(page.getByText('Certificado válido no registro de emissão.')).toBeVisible()
  await expect(page.getByText('Marina Costa',{ exact: true })).toBeVisible()
  await page.getByLabel('Código de autenticidade').fill('codigo-inexistente')
  await page.getByRole('button',{ name: 'Verificar',exact: true }).click()
  await expect(page.getByText('Certificado inexistente.')).toBeVisible()
})
